"""Generate the integer FOC tables stored in firmware Flash."""

import argparse
from math import atan, isqrt, pi, sin
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[1] / "firmware/Control/Src/foc_tables.h"


def array(name, values, c_type="uint16_t"):
    rows = [
        "    " + ", ".join(str(value) for value in values[start:start + 12]) + ","
        for start in range(0, len(values), 12)
    ]
    return f"static const {c_type} {name}[{len(values)}] = {{\n" + "\n".join(rows) + "\n};\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = (
        "/* Generated by tools/generate_foc_tables.py. All tables stay in .rodata. */\n"
        "#ifndef FOC_TABLES_H\n#define FOC_TABLES_H\n\n"
        "/* sin(phase * 2*pi/16384) in Q14, including both quadrant endpoints. */\n"
        + array("sine_quarter", [round(16384 * sin(i * pi / 8192)) for i in range(4097)])
        + "\n/* atan(ratio/1024) in 16384-count electrical turns. */\n"
        + array("atan_octant", [round(atan(i / 1024) * 8192 / pi) for i in range(1025)])
        + "\n/* Q31 reciprocals at the centers of 64-count bins in [32768,65535]. */\n"
        + array("atan_reciprocal", [round(2**31 / (64 * i + 32)) for i in range(512, 1024)])
        + "\n/* Upper root bounds for 22-bit bins of a normalized uint32_t. */\n"
        + array("sqrt_seed", [isqrt(((i + 1) << 22) - 1) + 1 for i in range(256, 1024)],
                "uint32_t")
        + "\n#endif\n"
    )
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("FOC tables differ. Run uv run --script tools/generate_foc_tables.py")
    else:
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
